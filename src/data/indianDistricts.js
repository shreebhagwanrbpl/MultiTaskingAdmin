// Flattened list of all states
export const ALL_INDIAN_STATES = Object.keys(INDIAN_STATES_DISTRICTS);

// Helper to get districts for a state
export function getDistrictsForState(stateName) {
  if (!stateName) return [];
  return INDIAN_STATES_DISTRICTS[stateName] || ['All Districts'];
}

// Helper to find state of a given district
export function findStateForDistrict(districtName) {
  if (!districtName) return 'All India (Pan-India HQ)';
  for (const [state, districts] of Object.entries(INDIAN_STATES_DISTRICTS)) {
    if (districts.some(d => d.toLowerCase() === districtName.toLowerCase())) {
      return state;
    }
  }
  return 'All India (Pan-India HQ)';
}

